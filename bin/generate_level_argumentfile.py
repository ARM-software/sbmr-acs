"""Generate SBMR-ACS Robot argument files for a selected SBMR level."""

import argparse
from pathlib import Path
import sys
import yaml


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_METADATA_PATH = SCRIPT_DIR.parent / "test_lists" / "rule_metadata.yaml"
VALID_SUITES = ("oob", "linux")


def load_metadata(metadata_path=DEFAULT_METADATA_PATH):
    """Load SBMR rule metadata from a YAML file."""
    with Path(metadata_path).open("r", encoding="utf-8") as metadata_file:
        metadata = yaml.safe_load(metadata_file)
    return metadata


def canonical_level(level, metadata):
    """Return the validated SBMR level, using the metadata default when omitted."""
    selected_level = level or metadata["default_level"]
    selected_level = selected_level.upper()
    if selected_level not in metadata["levels"]["order"]:
        valid_levels = ", ".join(metadata["levels"]["order"])
        raise ValueError(
            f"invalid level '{level}'; expected one of: {valid_levels}"
        )
    return selected_level


def level_index(level, metadata):
    """Return the ordering index for a validated SBMR level."""
    selected_level = canonical_level(level, metadata)
    return metadata["levels"]["order"].index(selected_level)


def included_rules(metadata, suite, level):
    """Yield metadata rules included for a suite at the selected level."""
    selected_index = level_index(level, metadata)
    for rule in metadata["rules"]:
        if suite not in rule.get("suites", {}):
            continue
        if level_index(rule["introduced"], metadata) <= selected_index:
            for cutoff in ("upgraded", "relaxed"):
                cutoff_level = rule.get(cutoff)
                if (
                    cutoff_level
                    and level_index(cutoff_level, metadata) <= selected_index
                ):
                    break
            else:
                yield rule


def unique_robot_include_tags(metadata, suite, level):
    """Return unique Robot include tags for a suite and level in metadata order."""
    tags = []
    seen_tags = set()
    for rule in included_rules(metadata, suite, level):
        for tag in rule["suites"][suite]:
            if tag in seen_tags:
                continue
            seen_tags.add(tag)
            tags.append(tag)
    return tags


def skip_on_failure_tags(metadata, suite, level):
    """Return included Robot tags that should be marked --skiponfailure."""
    skip_policy = metadata.get("skip_on_failure", {})
    skip_tags = set(skip_policy.get("always", []))

    include_tags = unique_robot_include_tags(metadata, suite, level)
    return [tag for tag in include_tags if tag in skip_tags]


def build_argument_lines(metadata, suite, level=None):
    """Build Robot argument-file lines for a suite and selected level."""
    if suite not in VALID_SUITES:
        valid_suites = ", ".join(VALID_SUITES)
        raise ValueError(f"invalid suite '{suite}'; expected one of: {valid_suites}")

    selected_level = canonical_level(level, metadata)
    lines = [
        "# Generated by bin/generate_level_argumentfile.py. Do not edit by hand.",
        f"# Suite: {suite}",
        f"# Level: {selected_level}",
    ]

    current_category = None
    emitted_tags = set()
    for rule in included_rules(metadata, suite, selected_level):
        # Some checklist rule IDs share one Robot tag; emit each tag only once.
        rule_tags = []
        for tag in rule["suites"][suite]:
            if tag in emitted_tags:
                continue
            emitted_tags.add(tag)
            rule_tags.append(tag)

        # If all tags for this rule were emitted by an earlier rule, avoid
        # adding an empty category section.
        if not rule_tags:
            continue

        category = rule["category"]
        # Preserve metadata order while grouping adjacent rules by category.
        if category != current_category:
            lines.extend(["", f"# {category}"])
            current_category = category
        for tag in rule_tags:
            lines.append(f"--include {tag}")

    # Keep soft-failure policy after includes so the generated file is easy to
    # scan and compare with the selected test set.
    skip_tags = skip_on_failure_tags(metadata, suite, selected_level)
    if skip_tags:
        lines.extend(["", "# Skip on failure"])
        for tag in skip_tags:
            lines.append(f"--skiponfailure {tag}")

    return selected_level, lines


def write_argument_file(metadata, suite, level, output_path):
    """Write a generated Robot argument file and return its selected level."""
    selected_level, lines = build_argument_lines(metadata, suite, level)
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return selected_level


def parse_args(argv):
    """Parse command-line arguments for the generator CLI."""
    parser = argparse.ArgumentParser(
        description="Generate an SBMR-ACS Robot argument file for a selected level."
    )
    parser.add_argument(
        "--suite",
        required=True,
        choices=VALID_SUITES,
        help="SBMR-ACS suite to generate arguments for.",
    )
    parser.add_argument(
        "--level",
        default=None,
        help="SBMR level to include through. Defaults to the metadata default.",
    )
    parser.add_argument(
        "--output",
        required=True,
        help="Path where the generated Robot argument file will be written.",
    )
    parser.add_argument(
        "--metadata",
        default=str(DEFAULT_METADATA_PATH),
        help="Path to the SBMR rule metadata YAML file.",
    )
    return parser.parse_args(argv)


def main(argv=None):
    """Run the generator CLI and return a process-style status code."""
    args = parse_args(argv)
    metadata = load_metadata(args.metadata)
    try:
        write_argument_file(metadata, args.suite, args.level, args.output)
    except ValueError as err:
        print(err, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
